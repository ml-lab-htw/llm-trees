"""LLMTreeClassifier: decision-tree induction via the two-step LLM workflow.

Step 1 asks the LLM for a human-readable decision tree; step 2 converts it
into a Python ``predict(X)`` function returning ``(prediction, nodes)``.
The function is compiled, validated on the fit rows (label mapping +
complexity constraints), and used for prediction.
"""

import time

import numpy as np
import pandas as pd
from sklearn.base import BaseEstimator, ClassifierMixin
from sklearn.utils.validation import check_is_fitted

from ._llm import make_client
from ._prompts import build_first_prompt, build_second_prompt
from ._tree import compile_tree_function
from ._tree_ast import leaf_index, leaves
from ._utils import (
    check_classification_target,
    check_complexity_param,
    check_feature_names,
    check_features,
    check_target,
    check_target_name,
    generate_tree_with_retry,
    map_label,
    resolve_feature_names,
    save_prompts,
)


class LLMTreeClassifier(ClassifierMixin, BaseEstimator):
    """Induce a decision tree with a large language model and predict with it.

    The tree is generated by the two-step LLM workflow (a readable decision
    tree first, then a Python function implementing it) and executed row-wise
    for prediction. No trees are written to disk.

    Parameters
    ----------
    target : dict
        One entry mapping the target column name to its description.
        Required: the LLM needs it to induce a meaningful tree. The
        key must match the name of ``y`` when ``y`` carries one
        (named Series or one-column DataFrame).

    features : dict
        One entry per feature mapping the column name to its description.
        Required: it must cover every feature of ``X``. Included in both
        step prompts, so the LLM sees each feature's name and description
        when inducing the tree.

    max_tree_depth : int or None, default=None
        Maximum tree depth requested in the prompt and enforced on the
        generated tree. None means no depth constraint.

    num_features : int or None, default=None
        Maximum number of distinct features requested in the prompt and
        enforced on the generated tree. None means no feature-count
        constraint. When either limit is set, a generated tree that cannot
        be parsed is rejected and generation is retried.

    prompt_file : str or bool, default=True
        Where to write the generated step prompts for inspection: True writes
        ``prompt.txt`` to the current working directory (your project root);
        a string writes to that path (parent directories are created);
        False disables the file.

    backend : str, default="openrouter"
        LLM backend: "openrouter" (the only supported backend; requires the
        ``OPENROUTER_API_KEY`` and ``OPENROUTER_MODEL`` environment variables).

    temperature : float, default=0.0
        Sampling temperature forwarded to the LLM backend.

    seed : int or None, default=None
        Sampling seed forwarded to the LLM backend.

    num_examples : int, default=1
        Number of example ``predict`` functions included in the prompts
        (0 disables examples).

    use_role_prompt : bool, default=False
        Whether to prefix the first prompt with the role prompt.

    num_retry_llm : int, default=10
        Total number of tree-generation attempts; a ``ValueError`` is raised
        if every attempt fails.

    Attributes
    ----------
    classes_ : ndarray of shape (n_classes,)
        Original target labels present in ``y``.

    feature_names_in_ : ndarray of shape (n_features,), dtype=object
        Feature names seen at fit time.

    support_ : ndarray of shape (sparsity,), dtype=object
        Feature names referenced by the induced tree, in first-use order.

    sparsity_ : int
        Number of features referenced by the induced tree.

    elapsed_time_ : float
        Wall-clock fit time in seconds (includes LLM calls).

    tree_code_ : str
        The compiled Python source of the induced ``predict`` function.

    tree_ : ParsedTree or None
        Parsed tree structure, or None when the generated function does not
        follow the expected ``nodes``/``if`` form (only possible when no
        complexity limit is set; ``predict_proba`` then raises).

    Notes
    -----
    ``predict_proba`` reports, for each sample, the fraction of fit samples in
    the same tree leaf per class (a leaf histogram, not calibrated
    probabilities). A leaf empty at fit time falls back to the overall class
    prior. It requires a parsable tree structure.
    """

    def __init__(
        self,
        target: dict,
        features: dict,
        max_tree_depth: int | None = None,
        num_features: int | None = None,
        prompt_file: str | bool = True,
        backend: str = "openrouter",
        temperature: float = 0.0,
        seed: int | None = None,
        num_examples: int = 1,
        use_role_prompt: bool = False,
        num_retry_llm: int = 10,
    ):
        self.target = target
        self.features = features
        self.max_tree_depth = max_tree_depth
        self.num_features = num_features
        self.prompt_file = prompt_file
        self.backend = backend
        self.temperature = temperature
        self.seed = seed
        self.num_examples = num_examples
        self.use_role_prompt = use_role_prompt
        self.num_retry_llm = num_retry_llm

    def __getstate__(self):
        # the compiled tree function is not picklable; ``tree_code_`` (the
        # stored source) is the single source of truth
        state = self.__dict__.copy()
        state.pop("_tree_fn", None)
        return state

    def __setstate__(self, state):
        self.__dict__.update(state)
        if state.get("tree_code_") is not None:
            self._tree_fn = compile_tree_function(state["tree_code_"])

    def fit(self, X, y):
        """Induce the tree on ``X`` / ``y`` via the two-step LLM workflow.

        Learned state is committed to the estimator only after a successful
        fit; a failed fit leaves the previous state (fitted or unfitted)
        untouched, so inference never sees a mixed old/new state.
        """
        if len(X) != len(y):
            raise ValueError(f"X has {len(X)} samples, but y has {len(y)} samples")
        start = time.monotonic()

        target_name, _target_desc = check_target(self.target)
        check_target_name(target_name, y)
        check_complexity_param(self.max_tree_depth, "max_tree_depth")
        check_complexity_param(self.num_features, "num_features")
        check_features(self.features)

        feature_names_in = resolve_feature_names(X, self.features)
        y = check_classification_target(y)
        classes = np.unique(y)

        X = self._as_frame(X, feature_names_in)
        features = {name: self.features[name] for name in feature_names_in}
        first_prompt = build_first_prompt(
            target=self.target,
            features=features,
            max_tree_depth=self.max_tree_depth,
            num_features=self.num_features,
            num_examples=self.num_examples,
            use_role_prompt=self.use_role_prompt,
        )
        second_prompt = build_second_prompt(
            target=self.target,
            features=features,
            num_examples=self.num_examples,
            max_tree_depth=self.max_tree_depth,
        )
        save_prompts(self.prompt_file, first_prompt, second_prompt)

        client = make_client(self.backend, self.temperature, self.seed)
        code, pt, fn = generate_tree_with_retry(
            client=client,
            first_prompt=first_prompt,
            second_prompt=second_prompt,
            X=X,
            classes=classes,
            max_tree_depth=self.max_tree_depth,
            num_features=self.num_features,
            num_retry_llm=self.num_retry_llm,
            numeric=False,
        )

        support = np.asarray(list(pt.features), dtype=object) if pt is not None else np.asarray([], dtype=object)

        n_classes = len(classes)
        if pt is not None:
            n_leaves = len(leaves(pt))
            counts = np.zeros((n_leaves, n_classes), dtype=float)
            class_idx = {c: i for i, c in enumerate(classes)}
            for i in range(len(X)):
                _pred, nodes = fn(X.iloc[i].to_dict())
                li = leaf_index(nodes, pt.structure)
                counts[li, class_idx[y[i]]] += 1
            leaf_class_counts = counts
        else:
            leaf_class_counts = None

        class_positions = np.searchsorted(classes, y)
        class_prior = np.bincount(class_positions, minlength=n_classes) / len(y)

        # commit learned state only after successful generation and validation
        self.feature_names_in_ = feature_names_in
        self.classes_ = classes
        self.tree_code_ = code
        self.tree_ = pt
        self._tree_fn = fn
        self.support_ = support
        self.sparsity_ = len(support)
        self._leaf_class_counts_ = leaf_class_counts
        self._class_prior_ = class_prior
        self.elapsed_time_ = time.monotonic() - start
        return self

    def _as_frame(self, X, feature_names_in) -> pd.DataFrame:
        """Validate feature names and return X as a DataFrame (row dicts)."""
        check_feature_names(X, feature_names_in)
        if not isinstance(X, pd.DataFrame):
            X = pd.DataFrame(X, columns=feature_names_in)
        return X

    def predict(self, X):
        """Predict original target labels for ``X`` using the induced tree.

        Returns an array whose dtype is preserved from ``classes_`` (e.g.
        ``int64`` for numeric targets, ``object`` for string labels), so the
        output is directly usable with sklearn metrics and ``score``.
        """
        check_is_fitted(self)
        X = self._as_frame(X, self.feature_names_in_)
        y_pred = np.empty(len(X), dtype=self.classes_.dtype)
        for i in range(len(X)):
            pred, _nodes = self._tree_fn(X.iloc[i].to_dict())
            y_pred[i] = map_label(pred, self.classes_)
        return y_pred

    def predict_proba(self, X):
        """Leaf class fractions for ``X`` (empty leaves fall back to the prior).

        The leaf the sample lands in must be readable from a structurally
        parsable tree; if the induced function was executable but unparsable
        (possible only when no complexity constraint was set, in which case
        ``tree_`` is ``None``) this raises ``RuntimeError``.

        Returns
        -------
        ndarray of shape (n_samples, n_classes)
            Fraction of fit samples of each class in the tree leaf the sample
            lands in; overall class prior for leaves empty at fit time.
        """
        check_is_fitted(self)
        if self.tree_ is None or self._leaf_class_counts_ is None:
            raise RuntimeError("predict_proba requires a parsable tree structure")
        X = self._as_frame(X, self.feature_names_in_)
        proba = np.zeros((len(X), len(self.classes_)))
        for i in range(len(X)):
            _pred, nodes = self._tree_fn(X.iloc[i].to_dict())
            leaf = self._leaf_class_counts_[leaf_index(nodes, self.tree_.structure)]
            proba[i] = leaf / leaf.sum() if leaf.sum() > 0 else self._class_prior_
        return proba
